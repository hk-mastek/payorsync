export function generateVarianceData(count: number = 2250): VarianceRecord[] {
  const records: VarianceRecord[] = [];
  const startDate = new Date('2024-12-01');
  const endDate = new Date('2025-12-31');
  const dateRange = endDate.getTime() - startDate.getTime();
  
  for (let i = 0; i < count; i++) {
    const seed = i + 1;
    
    const payorType = weightedRandomSelect(PAYOR_TYPES, seed);
    const matchingPayors = PAYORS.filter(p => p.type === payorType.type);
    const payor = matchingPayors[Math.floor(seededRandom(seed * 2) * matchingPayors.length)] || PAYORS[0];
    
    const state = weightedRandomSelect(STATES.map(s => ({ ...s, weight: s.weight })), seed * 3);
    const rootCause = weightedRandomSelect(ROOT_CAUSES, seed * 4);
    const subcategory = rootCause.subcategories[Math.floor(seededRandom(seed * 5) * rootCause.subcategories.length)];
    const agingBucket = weightedRandomSelect(AGING_BUCKETS, seed * 6);
    const status = weightedRandomSelect(STATUSES, seed * 7);
    
    const billedAmount = Math.round((150 + seededRandom(seed * 8) * 2350) * 100) / 100;
    const variancePercentage = 5 + seededRandom(seed * 9) * 45;
    const varianceAmount = Math.round(billedAmount * (variancePercentage / 100) * 100) / 100;
    const paidAmount = Math.round((billedAmount - varianceAmount) * 100) / 100;
    
    const varianceDate = new Date(startDate.getTime() + seededRandom(seed * 10) * dateRange);
    
    const agingDays = agingBucket.min + Math.floor(seededRandom(seed * 13) * (agingBucket.max - agingBucket.min));
    
    const dosDate = new Date(varianceDate);
    dosDate.setDate(dosDate.getDate() - Math.floor(seededRandom(seed * 11) * 30) - 7);
    
    const claimDate = new Date(dosDate);
    claimDate.setDate(claimDate.getDate() + Math.floor(seededRandom(seed * 12) * 14) + 1);
    
    let priority: 'High' | 'Medium' | 'Low' = 'Low';
    if (varianceAmount > 1000 || agingDays > 120) priority = 'High';
    else if (varianceAmount > 500 || agingDays > 60) priority = 'Medium';
    
    records.push({
      id: `V-${String(10001 + i).padStart(5, '0')}`,
      payorId: payor.id,
      payorName: payor.name,
      payorType: payor.type,
      state: state.code,
      stateName: state.name,
      rootCauseCategory: rootCause.category,
      rootCauseSubcategory: subcategory,
      billedAmount,
      paidAmount,
      varianceAmount,
      variancePercentage: Math.round(variancePercentage * 10) / 10,
      dateOfService: dosDate.toISOString().split('T')[0],
      claimSubmissionDate: claimDate.toISOString().split('T')[0],
      varianceIdentifiedDate: varianceDate.toISOString().split('T')[0],
      status: status.value,
      agingBucket: agingBucket.label,
      agingDays,
      patientName: PATIENT_NAMES[Math.floor(seededRandom(seed * 15) * PATIENT_NAMES.length)],
      priority,
      treatmentCount: 1 + Math.floor(seededRandom(seed * 14) * 5),
    });
  }
  
  return records;
}

export function calculateKPIs(data: VarianceRecord[]) {
  const openVariances = data.filter(v => v.status !== 'Resolved' && v.status !== 'Written Off');
  const resolvedVariances = data.filter(v => v.status === 'Resolved');
  const writtenOff = data.filter(v => v.status === 'Written Off');
  
  const today = new Date('2025-01-15');
  const weekAgo = new Date(today);
  weekAgo.setDate(weekAgo.getDate() - 7);
  
  const newThisWeek = data.filter(v => new Date(v.varianceIdentifiedDate) >= weekAgo).length;
  const resolvedThisWeek = resolvedVariances.filter(v => {
    const date = new Date(v.varianceIdentifiedDate);
    date.setDate(date.getDate() + v.agingDays);
    return date >= weekAgo;
  }).length;
  
  const totalVarianceAmount = openVariances.reduce((sum, v) => sum + v.varianceAmount, 0);
  const avgDaysToResolution = resolvedVariances.length > 0 
    ? resolvedVariances.reduce((sum, v) => sum + v.agingDays, 0) / resolvedVariances.length 
    : 0;
  
  const totalRecoverable = [...resolvedVariances, ...writtenOff].reduce((sum, v) => sum + v.varianceAmount, 0);
  const recovered = resolvedVariances.reduce((sum, v) => sum + v.varianceAmount, 0);
  const recoveryRate = totalRecoverable > 0 ? (recovered / totalRecoverable) * 100 : 0;
  
  return {
    totalOpenVariances: openVariances.length,
    totalVarianceAmount,
    newThisWeek,
    resolvedThisWeek,
    avgDaysToResolution: Math.round(avgDaysToResolution * 10) / 10,
    recoveryRate: Math.round(recoveryRate * 10) / 10,
  };
}

export function groupByPayorType(data: VarianceRecord[]) {
  const groups: Record<string, { count: number; amount: number }> = {};
  data.forEach(v => {
    if (!groups[v.payorType]) groups[v.payorType] = { count: 0, amount: 0 };
    groups[v.payorType].count++;
    groups[v.payorType].amount += v.varianceAmount;
  });
  return Object.entries(groups)
    .map(([type, data]) => ({ type, ...data }))
    .sort((a, b) => b.amount - a.amount);
}

export function groupByPayorWithType(data: VarianceRecord[]) {
  const typeGroups: Record<string, { count: number; amount: number; payors: Record<string, { name: string; count: number; amount: number }> }> = {};
  data.forEach(v => {
    if (!typeGroups[v.payorType]) {
      typeGroups[v.payorType] = { count: 0, amount: 0, payors: {} };
    }
    typeGroups[v.payorType].count++;
    typeGroups[v.payorType].amount += v.varianceAmount;
    
    if (!typeGroups[v.payorType].payors[v.payorId]) {
      typeGroups[v.payorType].payors[v.payorId] = { name: v.payorName, count: 0, amount: 0 };
    }
    typeGroups[v.payorType].payors[v.payorId].count++;
    typeGroups[v.payorType].payors[v.payorId].amount += v.varianceAmount;
  });
  
  return Object.entries(typeGroups)
    .map(([type, data]) => ({
      type,
      count: data.count,
      amount: data.amount,
      payors: Object.entries(data.payors)
        .map(([id, payor]) => ({ id, ...payor }))
        .sort((a, b) => b.amount - a.amount),
    }))
    .sort((a, b) => b.amount - a.amount);
}

